"""Run a retrieval ablation and write a Markdown table with the results.

The script is intentionally small: it calls the same runner the CLI uses, so a
number in the report can be reproduced from `artifacts/runs/` by hand.

    python scripts/run_ablation.py --data-dir datasets/scifact \
        --out reports/scifact-ablation.md
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from rag_eval_bench.evaluation.runner import run_experiment  # noqa: E402
from rag_eval_bench.storage import Store  # noqa: E402

CONFIGS: list[dict[str, str | int]] = [
    {"retriever": "bm25"},
    {"retriever": "dense"},
    {"retriever": "hybrid"},
    {"retriever": "hybrid", "reranker": "ms-marco-mini"},
]

CONFIG_LABELS = {
    ("bm25", None): "BM25",
    ("dense", None): "Dense (bi-encoder)",
    ("hybrid", None): "Hybrid (RRF)",
    ("hybrid", "ms-marco-mini"): "Hybrid + cross-encoder",
}


def percentile(values: list[int], share: float) -> int:
    if not values:
        return 0
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, round(share * (len(ordered) - 1))))
    return ordered[index]


def run_config(
    store: Store,
    *,
    artifacts: Path,
    config: dict[str, str | int],
    k: int,
    candidates: int,
    dataset: str,
) -> tuple[dict[str, object], list[int]]:
    retriever = str(config["retriever"])
    reranker = config.get("reranker")
    reranker_name = str(reranker) if reranker else None
    label = CONFIG_LABELS.get((retriever, reranker_name), retriever)
    record = run_experiment(
        store=store,
        artifacts_dir=artifacts,
        retriever=retriever,
        k=k,
        reranker=reranker_name,
        candidates=candidates if reranker_name else 0,
        name=f"ablation-{retriever}-{reranker_name or 'none'}",
    )
    latencies = [example.latency_ms for example in record.examples]
    row = {
        "label": label,
        "retriever": retriever,
        "reranker": reranker_name,
        "run_id": record.id,
        "dataset": dataset,
        "metrics": record.metrics,
        "p50_ms": median(latencies),
        "p95_ms": percentile(latencies, 0.95),
        "questions": len(record.examples),
    }
    return row, latencies


def render_markdown(
    rows: list[dict[str, object]],
    *,
    dataset: str,
    k: int,
    candidates: int,
    chunk_size: int,
    chunk_overlap: int,
) -> str:
    header = (
        "| Retrieval | Recall@5 | MRR@10 | retrieval, ms (mean) | rerank, ms (mean) | "
        "total p50, ms | total p95, ms |\n"
        "|---|---:|---:|---:|---:|---:|---:|\n"
    )
    lines = []
    for row in rows:
        metrics = row["metrics"]
        assert isinstance(metrics, dict)
        rerank_ms = metrics.get("rerank_ms", "—")
        lines.append(
            "| {label} | {recall:.3f} | {mrr:.3f} | {retrieval} | {rerank} | "
            "{p50:.0f} | {p95:.0f} |".format(
                label=row["label"],
                recall=metrics["recall_at_5"],
                mrr=metrics["mrr_at_10"],
                retrieval=metrics["retrieval_ms"],
                rerank=rerank_ms,
                p50=row["p50_ms"],
                p95=row["p95_ms"],
            )
        )
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    return (
        f"# Retrieval ablation: {dataset}\n\n"
        f"Generated by `scripts/run_ablation.py` on {stamp}.\n\n"
        f"- top k: {k}, reranker candidates: {candidates}\n"
        f"- chunks: {chunk_size} characters, {chunk_overlap} overlap\n"
        f"- generator: extractive baseline (its time is included in the totals)\n"
        f"- runs are stored in `artifacts/runs/` and named `ablation-*`\n\n"
        f"{header}{chr(10).join(lines)}\n\n"
        "Recall@5 and MRR@10 follow the runner: a hit is a retrieved chunk whose "
        "document is in the relevance judgements.\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=Path("datasets/scifact"))
    parser.add_argument("--dataset", default="scifact")
    parser.add_argument("--artifacts", type=Path, default=Path("artifacts"))
    parser.add_argument("--out", type=Path, default=Path("reports/scifact-ablation.md"))
    parser.add_argument("--k", type=int, default=5)
    parser.add_argument("--candidates", type=int, default=20)
    parser.add_argument("--chunk-size", type=int, default=400)
    parser.add_argument("--chunk-overlap", type=int, default=50)
    args = parser.parse_args(argv)

    store = Store(args.data_dir, args.artifacts)
    if not store.questions:
        print(f"no questions in {args.data_dir}; run fetch-data first", file=sys.stderr)
        return 2

    rows = []
    for config in CONFIGS:
        print(f"running {config}", flush=True)
        row, _ = run_config(
            store,
            artifacts=args.artifacts,
            config=config,
            k=args.k,
            candidates=args.candidates,
            dataset=args.dataset,
        )
        print(f"  {row['label']}: {row['metrics']}", flush=True)
        rows.append(row)

    markdown = render_markdown(
        rows,
        dataset=args.dataset,
        k=args.k,
        candidates=args.candidates,
        chunk_size=args.chunk_size,
        chunk_overlap=args.chunk_overlap,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown, encoding="utf-8")
    payload = {"dataset": args.dataset, "k": args.k, "rows": rows}
    args.out.with_suffix(".json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"written {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
